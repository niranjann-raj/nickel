import { test, expect } from '@playwright/test';
import { execSync } from 'child_process';
import path from 'path';

function getLatestOtp(email: string, purpose: 'register' | 'reset'): string {
  const backendDir = path.resolve(process.cwd(), 'backend');
  const cmd = `python get_otp.py "${email.toLowerCase()}" "${purpose}"`;
  return execSync(cmd, { cwd: backendDir }).toString().trim();
}

test.describe('Authentication', () => {
  const testEmail = process.env.TEST_USER_EMAIL || 'tracker_test@example.com';
  const testPassword = process.env.TEST_USER_PASSWORD || 'password123';

  test('Valid login succeeds', async ({ page }) => {
    await page.goto('/login');

    await page.getByPlaceholder(/you@example.com/i).fill(testEmail);
    await page.getByPlaceholder(/password/i).fill(testPassword);

    const loginBtn = page.getByRole('button', { name: /Continue with Email/i });
    await loginBtn.click();

    // Give it a moment to load
    await expect(page).toHaveURL(/.*\/dashboard/, { timeout: 25000 });
  });

  test('Invalid credentials are handled correctly', async ({ page }) => {
    await page.goto('/login');
    await page.getByPlaceholder(/you@example.com/i).fill('invalid_nonexistent_user@example.com');
    await page.getByPlaceholder(/password/i).fill('wrongpassword123');
    await page.getByRole('button', { name: /Continue with Email/i }).click();

    // Verify error message
    const errorMsg = page.locator('text=/Invalid|Incorrect|Error|not found/i').first();
    await expect(errorMsg).toBeVisible();
  });

  test('Login is rejected when password is mismatched for an existing account', async ({ page }) => {
    await page.goto('/login');

    // Fill valid email with wrong password
    await page.getByPlaceholder(/you@example.com/i).fill(testEmail);
    await page.getByPlaceholder(/password/i).fill('completely_mismatched_password_123');

    await page.getByRole('button', { name: /Continue with Email/i }).click();

    // Verify error banner is shown
    const errorMsg = page.locator('text=/Incorrect email or password|Invalid credentials/i').first();
    await expect(errorMsg).toBeVisible({ timeout: 10000 });

    // Assert URL remains on login page
    expect(page.url()).toContain('/login');
  });

  test('Sign up flow verifies email with OTP and rejects incorrect OTP', async ({ page }) => {
    const signupEmail = `pw_signup_${Date.now()}@example.com`;
    const signupName = 'Playwright Test User';
    const signupPassword = 'ValidPassword123!';

    await page.goto('/signup');

    // Fill registration form
    await page.getByPlaceholder(/Full Name/i).fill(signupName);
    await page.getByPlaceholder(/you@example.com/i).fill(signupEmail);

    // Click "Verify" button to request registration OTP
    await page.getByRole('button', { name: /Verify/i }).click();

    // OTP input appears
    const otpInput = page.getByPlaceholder(/Enter 6-digit OTP/i);
    await expect(otpInput).toBeVisible({ timeout: 10000 });

    // 1. Enter an incorrect OTP and assert it is rejected
    await otpInput.fill('000000');
    await page.getByRole('button', { name: 'Confirm' }).click();
    await expect(page.getByText(/Invalid OTP/i)).toBeVisible({ timeout: 10000 });

    // 2. Query real OTP generated by the backend
    const realOtp = getLatestOtp(signupEmail, 'register');
    expect(realOtp).toBeTruthy();

    // 3. Fill the correct OTP and confirm
    await otpInput.clear();
    await otpInput.fill(realOtp);
    await page.getByRole('button', { name: 'Confirm' }).click();

    // Email field becomes disabled upon successful verification
    await expect(page.getByPlaceholder(/you@example.com/i)).toBeDisabled({ timeout: 10000 });

    // 4. Fill password and submit signup
    await page.getByPlaceholder(/Min\. 6 characters/i).fill(signupPassword);
    await page.getByRole('button', { name: /Sign Up with Email/i }).click();

    // Redirection to dashboard
    await expect(page).toHaveURL(/.*\/dashboard/, { timeout: 25000 });

    // Clean up created user from database
    const backendDir = path.resolve(process.cwd(), 'backend');
    execSync(`python cleanup_test_user.py "${signupEmail}"`, { cwd: backendDir });
  });

  test('Forgot password flow verifies OTP, rejects incorrect OTP, and resets password', async ({ page }) => {
    // Dedicated account so primary tracker_test user credentials are never corrupted
    const forgotEmail = 'forgot_test@example.com';

    await page.goto('/login');

    // 1. Click "Forgot password?"
    await page.getByRole('button', { name: /Forgot password\?/i }).click();
    await expect(page.getByRole('heading', { name: /Reset your password/i })).toBeVisible();

    // 2. Request OTP for dedicated forgot test user
    await page.getByPlaceholder(/you@example.com/i).fill(forgotEmail);
    await page.getByRole('button', { name: /Send OTP/i }).click();

    // Wait for step 2: Check your email
    await expect(page.getByRole('heading', { name: /Check your email/i })).toBeVisible({ timeout: 10000 });
    const otpInput = page.getByPlaceholder('------');

    // 3. Enter incorrect OTP and assert it is rejected
    await otpInput.fill('000000');
    await page.getByRole('button', { name: /Verify OTP/i }).click();
    await expect(page.getByText(/Invalid OTP/i)).toBeVisible({ timeout: 10000 });

    // 4. Fetch the real OTP from database using fast psycopg2 helper
    const realOtp = getLatestOtp(forgotEmail, 'reset');
    expect(realOtp).toBeTruthy();

    // 5. Fill real OTP and verify
    await otpInput.clear();
    await otpInput.fill(realOtp);
    await page.getByRole('button', { name: /Verify OTP/i }).click();

    // 6. Step 3: Create a new password
    await expect(page.getByRole('heading', { name: /Create a new password/i })).toBeVisible({ timeout: 10000 });
    await page.getByPlaceholder('New password', { exact: true }).fill('newpassword123');
    await page.getByPlaceholder(/Confirm new password/i).fill('newpassword123');
    await page.getByRole('button', { name: /Reset Password/i }).click();

    // 7. Verify success screen and navigate back to Sign In
    await expect(page.getByRole('heading', { name: /Password reset successfully/i })).toBeVisible({ timeout: 10000 });
    await page.getByRole('button', { name: /Back to Sign In/i }).click();
    await expect(page.getByRole('heading', { name: /Sign in to Account/i })).toBeVisible();

    // 8. Restore the test password back to password123
    const backendDir = path.resolve(process.cwd(), 'backend');
    execSync('python seed_tracker_test_user.py', { cwd: backendDir });
  });
});
